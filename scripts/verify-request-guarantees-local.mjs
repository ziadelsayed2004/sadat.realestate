import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import mongoose, { Types } from 'mongoose';
import { createHmacAccessTokenService } from '../apps/api/src/modules/auth/crypto.ts';
import { createAuditModels } from '../apps/api/src/modules/audit/models.ts';
import { createMongooseAuditWriter } from '../apps/api/src/modules/audit/writer.ts';
import { createRbacRuntime } from '../apps/api/src/modules/rbac/runtime.ts';
import { createViewingRuntime } from '../apps/api/src/modules/viewings/runtime.ts';
import { createRequestRuntime } from '../apps/api/src/modules/requests/runtime.ts';
import { createApiServer, startApiServer, stopApiServer } from '../apps/api/src/server.ts';

// This verifier never accepts a remote URI or touches the local preview/production database.
const database = `request_guarantees_${Date.now()}`;
const connection = await mongoose.createConnection(`mongodb://127.0.0.1:27018/${database}?replicaSet=rs0`).asPromise();
const evidence = { environment: 'isolated-local-MongoDB-rs0-real-HTTP', database, testedAt: new Date().toISOString(),
  commit: execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim(), worktreeChanges: true, checks: [], status: 'RUNNING' };
let server;
try {
  const accessTokens = createHmacAccessTokenService(randomBytes(32), 3600);
  const auditModels = createAuditModels(connection);
  await auditModels.AuditLog.init();
  const durableAudit = createMongooseAuditWriter(auditModels);
  let failAudit = false;
  const audit = { async record(entry, session) {
    const id = await durableAudit.record(entry, session);
    if (failAudit) throw new Error('INJECTED_AUDIT_FAILURE');
    return id;
  } };
  const rbac = createRbacRuntime(connection, accessTokens, audit);
  const requests = createRequestRuntime(connection, accessTokens, rbac.service, audit);
  const viewings = createViewingRuntime(connection, accessTokens, rbac.service, audit);
  const ids = { seeker: new Types.ObjectId(), other: new Types.ObjectId(), admin: new Types.ObjectId(), role: new Types.ObjectId() };
  await connection.collection('users').insertMany(['seeker', 'other', 'admin'].map(name => ({ _id: ids[name], roleType: name === 'admin' ? 'admin' : 'seeker', status: 'verified' })));
  const permissions = ['admin:requests.view', 'admin:requests.manage', 'admin:requests.assign', 'admin:requests.notes'];
  await connection.collection('roles').insertOne({ _id: ids.role, name: 'Local request reviewer', nameKey: 'local-request-reviewer', accessMode: 'custom', active: true, permissions, createdAt: new Date(), updatedAt: new Date(), version: 0 });
  await connection.collection('admin_role_assignments').insertOne({ adminUserId: ids.admin, roleIds: [ids.role] });
  const tokens = Object.fromEntries(['seeker', 'other', 'admin'].map(name => [name, accessTokens.issue({ id: ids[name].toHexString(), roleType: name === 'admin' ? 'admin' : 'seeker', status: 'verified' }, new Types.ObjectId().toHexString(), new Date())]));
  server = createApiServer({ database: { isReady: async () => true }, requests, viewings });
  const address = await startApiServer(server, { host: '127.0.0.1', port: 0 });
  const base = `http://127.0.0.1:${address.port}/api/v1`;
  const call = async (actor, path, body) => {
    const response = await fetch(`${base}${path}`, { method: body === undefined ? 'GET' : 'POST', headers: { authorization: `Bearer ${tokens[actor]}`, 'content-type': 'application/json' }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    return { status: response.status, body: await response.json() };
  };
  const duplicates = await Promise.all([0, 1].map(() => call('seeker', '/seeker/contact-requests', { message: 'Isolated request guarantees verification' })));
  assert.deepEqual(duplicates.map(result => result.status).sort(), [201, 409]);
  const created = duplicates.find(result => result.status === 201);
  assert.equal(await connection.collection('requests').countDocuments(), 1);
  evidence.checks.push('concurrent_identical_creation_one_201_one_409_one_record');
  const id = created.body.data.id;
  const path = `/admin/requests/${id}`;
  const countAudit = () => auditModels.AuditLog.countDocuments({ targetId: id });
  assert.equal((await call('other', `/seeker/requests/${id}`)).status, 404);
  assert.equal((await call('other', `/seeker/requests/${id}/transitions`, { transition: 'cancel', reason: 'Attempt foreign cancellation', expectedVersion: 0 })).status, 404);
  evidence.checks.push('foreign_request_read_and_cancel_404');
  await connection.collection('users').updateOne({ _id: ids.seeker }, { $set: { status: 'suspended' } });
  assert.equal((await call('seeker', `/seeker/requests/${id}`)).status, 403);
  await connection.collection('users').updateOne({ _id: ids.seeker }, { $set: { status: 'verified' } });
  await connection.collection('users').updateOne({ _id: ids.admin }, { $set: { status: 'suspended' } });
  assert.equal((await call('admin', path)).status, 403);
  await connection.collection('users').updateOne({ _id: ids.admin }, { $set: { status: 'verified' } });
  evidence.checks.push('current_account_status_overrides_previously_issued_tokens');
  await connection.collection('roles').updateOne({ _id: ids.role }, { $set: { permissions: ['admin:requests.view'] } });
  assert.equal((await call('admin', path)).status, 200);
  const decision = { transition: 'start_review', reason: 'Review customer request', expectedVersion: 0 };
  assert.equal((await call('admin', `${path}/transitions`, decision)).status, 403);
  await connection.collection('roles').updateOne({ _id: ids.role }, { $set: { permissions } });
  evidence.checks.push('live_RBAC_revocation_denies_write_keeps_authorized_read');
  assert.equal((await call('admin', `${path}/transitions`, { transition: 'start_review', expectedVersion: 0 })).status, 400);
  assert.equal(await countAudit(), 0);
  failAudit = true;
  assert.equal((await call('admin', `${path}/transitions`, decision)).status, 500);
  assert.equal((await connection.collection('requests').findOne({ _id: new Types.ObjectId(id) })).version, 0);
  assert.equal(await countAudit(), 0);
  failAudit = false;
  evidence.checks.push('missing_reason_400', 'audit_failure_rolls_back_both_mutation_and_inserted_audit');
  const raced = await Promise.all([call('admin', `${path}/transitions`, decision), call('admin', `${path}/transitions`, decision)]);
  assert.deepEqual(raced.map(item => item.status).sort(), [200, 409]);
  assert.equal(await countAudit(), 1);
  assert.equal((await call('admin', `${path}/transitions`, decision)).status, 409);
  assert.equal(await countAudit(), 1);
  const entry = await auditModels.AuditLog.findOne({ targetId: id }).lean();
  assert.equal(entry.reason, decision.reason);
  assert.equal(entry.actorId.toHexString(), ids.admin.toHexString());
  assert.equal(entry.before.version, 0);
  assert.equal(entry.after.version, 1);
  assert.match(entry.traceId, /^[a-f0-9]{32}$/);
  evidence.checks.push('concurrent_decisions_one_success_one_409_one_audit', 'replayed_decision_no_duplicate_effect_or_audit', 'durable_actor_reason_versions_and_trace');
  const assignment = { assigneeId: ids.admin.toHexString(), expectedVersion: 1, reason: 'Assign verified reviewer' };
  failAudit = true;
  assert.equal((await call('admin', `${path}/assign`, assignment)).status, 500);
  assert.equal((await connection.collection('requests').findOne({ _id: new Types.ObjectId(id) })).assignedTo, undefined);
  failAudit = false;
  assert.equal((await call('admin', `${path}/assign`, assignment)).status, 200);
  assert.equal((await call('admin', `${path}/assign`, assignment)).status, 409);
  const note = { body: 'Private review note', expectedVersion: 2 };
  failAudit = true;
  assert.equal((await call('admin', `${path}/notes`, note)).status, 500);
  assert.equal((await connection.collection('requests').findOne({ _id: new Types.ObjectId(id) })).internalNotes, undefined);
  failAudit = false;
  assert.equal((await call('admin', `${path}/notes`, note)).status, 200);
  assert.equal((await call('admin', `${path}/notes`, note)).status, 409);
  assert.equal(await countAudit(), 3);
  assert.equal((await connection.collection('requests').findOne({ _id: new Types.ObjectId(id) })).internalNotes.length, 1);
  assert.equal(JSON.stringify((await call('seeker', `/seeker/requests/${id}`)).body).includes('Private review note'), false);
  evidence.checks.push('assignment_and_note_atomic_audit_rollback_and_replay_409', 'private_note_hidden_from_seeker');
  assert.equal((await call('admin', '/admin/viewings')).status, 403);
  await connection.collection('roles').updateOne({ _id: ids.role }, { $set: { permissions: [...permissions, 'admin:viewings.view'] } });
  assert.equal((await call('admin', '/admin/viewings')).status, 200);
  await connection.collection('users').updateOne({ _id: ids.admin }, { $set: { status: 'suspended' } });
  assert.equal((await call('admin', '/admin/viewings')).status, 403);
  await connection.collection('users').updateOne({ _id: ids.admin }, { $set: { status: 'verified' } });
  evidence.checks.push('viewing_admin_requires_own_permission_and_current_active_account');
  const providerId = new Types.ObjectId();
  const propertyId = new Types.ObjectId();
  await connection.collection('users').insertOne({ _id: providerId, roleType: 'provider', status: 'verified' });
  await connection.collection('properties').insertOne({ _id: propertyId, providerId, status: 'published', active: true });
  tokens.provider = accessTokens.issue({ id: providerId.toHexString(), roleType: 'provider', status: 'verified' }, new Types.ObjectId().toHexString(), new Date());
  const future = new Date(Date.now() + 86400000).toISOString();
  const viewing = await call('seeker', '/seeker/viewings', { propertyId: propertyId.toHexString(), requestedAt: future, timezone: 'Africa/Cairo' });
  assert.equal(viewing.status, 201);
  const viewingId = viewing.body.data.id;
  const viewingPath = `/provider/viewings/${viewingId}/transitions`;
  const confirmation = { action: 'confirm', expectedVersion: 0 };
  failAudit = true;
  assert.equal((await call('provider', viewingPath, confirmation)).status, 500);
  assert.equal((await connection.collection('viewings').findOne({ _id: new Types.ObjectId(viewingId) })).version, 0);
  assert.equal(await auditModels.AuditLog.countDocuments({ targetId: viewingId }), 0);
  failAudit = false;
  const viewingRace = await Promise.all([call('provider', viewingPath, confirmation), call('provider', viewingPath, confirmation)]);
  assert.deepEqual(viewingRace.map(result => result.status).sort(), [200, 409]);
  assert.equal(await auditModels.AuditLog.countDocuments({ targetId: viewingId }), 1);
  assert.equal((await call('provider', viewingPath, { action: 'reschedule', requestedAt: '2020-01-01T10:00:00Z', timezone: 'UTC', expectedVersion: 1 })).status, 409);
  assert.equal((await call('provider', viewingPath, { action: 'cancel', expectedVersion: 1 })).status, 400);
  const cancellation = await call('provider', viewingPath, { action: 'cancel', reason: 'Customer requested cancellation', expectedVersion: 1 });
  assert.equal(cancellation.status, 200);
  const viewingAudit = await auditModels.AuditLog.findOne({ targetId: viewingId, action: 'viewing.cancel' }).lean();
  assert.equal(viewingAudit.reason, 'Customer requested cancellation');
  assert.equal(viewingAudit.actorId.toHexString(), providerId.toHexString());
  evidence.checks.push('viewing_audit_failure_rolls_back_mutation_and_audit', 'viewing_concurrent_confirmation_one_200_one_409', 'viewing_past_reschedule_rejected', 'viewing_cancellation_reason_persisted');
  evidence.status = 'PASS_LOCAL';
} catch (error) {
  evidence.status = 'FAIL_LOCAL';
  evidence.error = error.message;
  throw error;
} finally {
  if (server) await stopApiServer(server);
  await connection.close();
  await mkdir('docs/quality/guide-runs', { recursive: true });
  await writeFile('docs/quality/guide-runs/request-guarantees-local-latest.json', `${JSON.stringify(evidence, null, 2)}\n`);
}
console.log(JSON.stringify(evidence, null, 2));
