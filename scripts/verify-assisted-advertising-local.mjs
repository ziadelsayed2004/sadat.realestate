import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import mongoose from 'mongoose';
import { createAuditModels } from '../apps/api/src/modules/audit/models.ts';
import { createMongooseAuditWriter } from '../apps/api/src/modules/audit/writer.ts';
import { createAdSettingsService } from '../apps/api/src/modules/ads/service.ts';
import { createMongooseAdRequestRepository, createMongooseAdAdminRequestRepository, createMongooseAdQuoteRepository, createMongooseAdCalendarRepository } from '../apps/api/src/modules/ads/repository.ts';
import { createProviderAdvertisingModels } from '../apps/api/src/modules/provider/advertising-models.ts';
import { createMongooseProviderAdvertisingSource } from '../apps/api/src/modules/provider/advertising-repository.ts';
import { createProviderAdvertisingProjectionService } from '../apps/api/src/modules/provider/advertising.ts';

const connection = await mongoose.createConnection(`mongodb://127.0.0.1:27018/assisted_ads_${randomUUID().replaceAll('-', '')}?replicaSet=rs0`).asPromise();
connection.base.set('transactionAsyncLocalStorage', true);
const report = { status: 'RUNNING', environment: 'isolated-local-MongoDB', mockedRoutes: false, fixtureNote: 'Approved clean payment proof inserted as a fixture; this run tests the scheduling guard, not upload scanning or bank verification.', startedAt: new Date().toISOString(), checks: [], cleanup: false };
try {
  const models = createProviderAdvertisingModels(connection);
  const audits = createAuditModels(connection);
  await Promise.all([models.AdRequest.init(), models.AdQuote.init(), models.AdSchedule.init(), models.PaymentProof.init(), audits.AuditLog.init()]);
  const provider = { role: 'provider', status: 'verified', sub: new mongoose.Types.ObjectId().toHexString() };
  const adminId = new mongoose.Types.ObjectId().toHexString();
  const now = new Date();
  const future = days => new Date(now.getTime() + days * 86400000).toISOString();
  const workflow = createAdSettingsService({ requestRepository: createMongooseAdRequestRepository(connection, models), quoteRepository: createMongooseAdQuoteRepository(connection, models), hasActivePlacement: key => key === 'homepage.hero', now: () => now });
  const request = await workflow.createRequest(provider, { requestMode: 'assisted', purpose: 'Apartment in Sadat City', contactPhone: '٠١٢٣٤٥٦٧٨٩٠' });
  assert.equal(request.status, 'review');
  assert.equal(request.contactPhone, '+201234567890');
  assert.equal(request.placementKey, undefined);
  assert.equal(request.intervalStart, undefined);
  const projection = createProviderAdvertisingProjectionService({ source: createMongooseProviderAdvertisingSource(connection, models) });
  assert.equal((await projection.get(provider, request.id)).contactPhone, '+201234567890');
  assert.equal((await projection.list(provider, {})).total, 1);
  await assert.rejects(() => projection.get({ ...provider, sub: new mongoose.Types.ObjectId().toHexString() }, request.id));
  report.checks.push('direct_review_with_normalized_phone_and_owner_scoped_projection_without_fake_schedule');
  const reviews = createMongooseAdAdminRequestRepository(connection, models, createMongooseAuditWriter(audits));
  await reviews.reviewAdminRequest(request.id, 0, 'waiting_pricing', 'Contacted provider and agreed campaign', now, { actorId: adminId, requestId: 'assisted-ad-review', traceId: 'a'.repeat(32) });
  const quoteInput = { requestId: request.id, currency: 'EGP', lineItems: [{ description: 'Homepage advertisement', quantity: 1, unitAmountMinor: 125050 }], validUntil: future(2), terms: 'Activate after administrative approval of payment' };
  await assert.rejects(() => workflow.issueQuote({ role: 'admin', status: 'verified', sub: adminId }, quoteInput));
  assert.equal(await models.AdQuote.countDocuments(), 0);
  const quote = await workflow.issueQuote({ role: 'admin', status: 'verified', sub: adminId }, { ...quoteInput, campaign: { placementKey: 'homepage.hero', intervalStart: future(3), intervalEnd: future(10) } });
  assert.equal(quote.totalMinor, 125050);
  assert.equal((await projection.get(provider, request.id)).intervalStart, future(3));
  assert.equal(await audits.AuditLog.countDocuments(), 1);
  report.checks.push('administrator_campaign_and_quote_saved_atomically_with_audited_request_review');
  await workflow.acceptQuote(provider, request.id, { action: 'accept', expectedVersion: quote.version });
  const current = await projection.get(provider, request.id);
  assert.equal(current.status, 'waiting_payment');
  const calendar = createMongooseAdCalendarRepository(connection, models);
  await assert.rejects(() => calendar.schedule(request.id, current.version));
  assert.equal(await models.AdSchedule.countDocuments(), 0);
  await models.PaymentProof.create({ adRequestId: request.id, providerId: provider.sub, paymentMethod: 'bank_transfer', originalFilename: 'receipt.pdf', normalizedExtension: '.pdf', detectedMime: 'application/pdf', byteSize: 4, sha256: 'a'.repeat(64), version: 1, securityState: 'clean', status: 'approved', reviewHistory: [{ action: 'approve', actorId: adminId, reason: 'Payment checked', version: 1, createdAt: now }], uploadedAt: now, active: true, idempotentReplay: false });
  const event = await calendar.schedule(request.id, current.version);
  assert.equal(event.timezone, 'Africa/Cairo');
  assert.equal(event.status, 'scheduled');
  report.checks.push('acceptance_is_not_payment_scheduling_requires_own_clean_approved_proof');
  report.status = 'PASS_LOCAL';
} finally {
  await connection.dropDatabase();
  await connection.close();
  report.cleanup = true;
}
await writeFile('docs/quality/guide-runs/assisted-advertising-local-latest.json', JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report));
