import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import mongoose, { Types } from 'mongoose';
import { planTrialCleanup, applyTrialCleanup } from './trial-content-cleanup.mjs';
import { createIdentitySubscriptionService } from '../apps/api/src/modules/provider/identity-subscription.ts';
import { deliverDueIdentityNotifications } from '../apps/api/src/modules/provider/subscription-notifications.ts';
import { createProviderVisibilityReader } from '../apps/api/src/modules/provider/visibility.ts';
import { createOrganizationManager } from '../apps/api/src/modules/accounts/organization-management.ts';
import { individualPublicIdentity } from '../apps/api/src/modules/public/identity.ts';
import { createMongoosePublicHomepageRepository, publicHomepageProjection } from '../apps/api/src/modules/public/homepage.ts';
import { createMongooseAdBannerRepository } from '../apps/api/src/modules/ads/banner-repository.ts';
import { readPublishedBannerRows } from '../apps/api/src/modules/ads/banner-management.ts';

const dbName = `owner_oct24_${randomUUID().replaceAll('-', '')}`;
const db = await mongoose.createConnection(`mongodb://127.0.0.1:27018/${dbName}?replicaSet=rs0`).asPromise();
const report = { status: 'RUNNING', environment: 'isolated-local-MongoDB', mockedDatabase: false, checks: [], cleanup: false };
const admin = new Types.ObjectId(), now = new Date(), context = { requestId: 'owner-oct24', traceId: 'a'.repeat(32) };
let failAudit = false;
const authorization = { async authorize() { return true; } };
const audit = { async record(value, session) { if (failAudit) throw new Error('INJECTED_AUDIT_FAILURE'); const row = await db.collection('audit_logs').insertOne(value, session ? { session } : {}); return String(row.insertedId); } };
const output = '.tmp/owner-oct24-guarantees';
await mkdir(output, { recursive: true });
try {
  await db.collection('users').insertOne({ _id: admin, roleType: 'admin', normalizedEmail: 'real-admin@example.invalid', status: 'verified' });
  await db.collection('admin_credentials').insertOne({ userId: admin, passwordHash: 'preserve-admin' });
  await db.collection('admin_settings').insertOne({ namespace: 'properties', values: { max_images: 50 } });
  const service = createIdentitySubscriptionService(db, authorization, audit);
  const manager = createOrganizationManager(db, authorization, audit);
  for (const type of ['individual_broker', 'brokerage_office', 'developer_company']) {
    const user = new Types.ObjectId(), profile = new Types.ObjectId(), application = new Types.ObjectId(), photo = new Types.ObjectId();
    await db.collection('users').insertOne({ _id: user, roleType: 'provider', status: 'verified', deletedAt: null });
    await db.collection('provider_profiles').insertOne({ _id: profile, userId: user, providerType: type, status: 'approved', version: 0 });
    await db.collection('provider_applications').insertOne({ _id: application, userId: user, providerType: type, status: 'approved', displayName: 'Local trial identity' });
    await db.collection('organization_photos').insertOne({ _id: photo, createdBy: user, storageKey: 'test-only-private-key' });
    let subscription = await service.read(String(admin), String(application));
    assert.equal(subscription.visible, false);
    const input = { expectedVersion: subscription.version, status: 'active', paymentConfirmed: true, startAt: new Date(now.getTime() - 60_000).toISOString(), endAt: new Date(now.getTime() + 3600_000).toISOString() };
    subscription = await service.put(String(admin), String(application), input, context);
    assert.equal(subscription.visible, true);
    assert.equal((await service.read(String(user), String(user), true)).canEditIdentity, true);
    assert.equal((await createProviderVisibilityReader(db).read(String(user))).customerIdentity, false);
    assert.equal(await db.collection('notifications').countDocuments({ recipientId: user, type: 'provider.identity_subscription.activated' }), 1);
    await assert.rejects(service.put(String(admin), String(application), input, context), /conflict/);
    assert.equal(await db.collection('notifications').countDocuments({ recipientId: user }), 1);
    subscription = await service.put(String(admin), String(user), { ...input, expectedVersion: subscription.version }, context);
    await deliverDueIdentityNotifications(db, now);
    assert.equal(await db.collection('notifications').countDocuments({ recipientId: user }), 1, 'Saving unchanged dates must not invent a renewal');
    const initial = await manager(String(user), String(user), undefined, undefined, true);
    const imageUrl = `/api/v1/public/organization-photos/${photo}`;
    const edited = await manager(String(user), String(user), { version: initial.version, name: { ar: 'هوية محلية حقيقية', en: 'Edited local identity' }, logoUrl: imageUrl, imageUrl, reason: 'Local subscription identity verification' }, context, true);
    assert.equal(edited.name.en, 'Edited local identity');
    if (type === 'individual_broker') assert.equal((await individualPublicIdentity(db, user)).sourceImageUrl, imageUrl);
    else assert.equal((await db.collection('organizations').findOne({ _id: profile })).imageUrl, imageUrl);
    const otherPhoto = new Types.ObjectId();
    await db.collection('organization_photos').insertOne({ _id: otherPhoto, createdBy: admin, storageKey: 'another-owner' });
    await assert.rejects(manager(String(user), String(user), { version: edited.version, logoUrl: `/api/v1/public/organization-photos/${otherPhoto}`, reason: 'Reject another owner photo' }, context, true), /validation/);
    subscription = await service.put(String(admin), String(user), { ...input, expectedVersion: subscription.version, endAt: new Date(now.getTime() + 7200_000).toISOString() }, context);
    assert.equal(await db.collection('notifications').countDocuments({ recipientId: user, type: 'provider.identity_subscription.renewed' }), 1);
    await deliverDueIdentityNotifications(db, new Date(now.getTime() + 7200_001));
    await deliverDueIdentityNotifications(db, new Date(now.getTime() + 7200_002));
    assert.equal(await db.collection('notifications').countDocuments({ recipientId: user, type: 'provider.identity_subscription.expired' }), 1);
    assert.equal((await createProviderVisibilityReader(db, () => new Date(now.getTime() + 7200_001)).read(String(user))).publicIdentity, false);
    const future = { ...input, expectedVersion: subscription.version, startAt: new Date(now.getTime() + 10_000_000).toISOString(), endAt: new Date(now.getTime() + 20_000_000).toISOString() };
    subscription = await service.put(String(admin), String(user), future, context);
    assert.equal(subscription.visible, false);
    assert.equal(await db.collection('notifications').countDocuments({ recipientId: user, type: 'provider.identity_subscription.scheduled' }), 1);
    await deliverDueIdentityNotifications(db, new Date(now.getTime() + 10_000_001));
    await deliverDueIdentityNotifications(db, new Date(now.getTime() + 10_000_002));
    assert.equal(await db.collection('notifications').countDocuments({ recipientId: user, type: 'provider.identity_subscription.activated' }), 2);
    failAudit = true;
    await assert.rejects(service.put(String(admin), String(user), { ...input, expectedVersion: subscription.version }, context), /INJECTED_AUDIT_FAILURE/);
    failAudit = false;
    assert.equal((await service.read(String(admin), String(user))).version, subscription.version);
    assert.equal(await db.collection('notifications').countDocuments({ recipientId: user, type: 'provider.identity_subscription.activated' }), 2);
    report.checks.push(`${type}: canonical account notification, active/renewed/scheduled/expired, deduplicated sweeps, no lead access, owned profile image edit, foreign image denied, audit rollback`);
  }
  const category = new Types.ObjectId(), article = new Types.ObjectId();
  await db.collection('article_categories').insertOne({ _id: category, active: true });
  await db.collection('articles').insertOne({ _id: article, categoryId: category, slug: 'real-owner-article', title: { ar: 'مقال تجريبي محلي', en: 'Real local article' }, body: { en: '<p>A real article excerpt.</p>' }, status: 'published', updatedAt: now });
  const homepage = async () => publicHomepageProjection(await createMongoosePublicHomepageRepository(db).read());
  let home = await homepage();
  assert.equal(home.content.find(row => row.key === `article_${article}`).targetUrl, '/articles/real-owner-article');
  assert.equal(home.content.find(row => row.key === `article_${article}`).body.en, 'A real article excerpt.');
  await db.collection('article_categories').updateOne({ _id: category }, { $set: { active: false } });
  assert.equal((await homepage()).content.some(row => row.key === `article_${article}`), false);
  await db.collection('article_categories').updateOne({ _id: category }, { $set: { active: true } });
  await db.collection('articles').updateOne({ _id: article }, { $set: { status: 'archived' } });
  assert.equal((await homepage()).content.some(row => row.key === `article_${article}`), false);
  report.checks.push('Published article appears with correct link and excerpt; inactive category and archive remove it');
  const banners = createMongooseAdBannerRepository(db, audit);
  await db.collection('ad_placements').insertOne({ key: 'homepage.hero', surface: 'homepage', active: true, sortOrder: 0 });
  await db.collection('ad_settings').insertOne({ enabled: true, allowedSurfaces: ['homepage'], maxActiveBanners: 5 });
  for (const keepOriginalHero of [true, false]) {
    const banner = await banners.createBanner(String(admin), { placementKey: 'homepage.hero', title: { en: 'Owner banner' }, startAt: new Date(now.getTime() - 60_000).toISOString(), endAt: new Date(now.getTime() + 3600_000).toISOString(), keepOriginalHero }, now, context);
    const media = await banners.createBannerMedia(String(admin), banner.id, { url: 'https://example.com/banner.png', mime: 'image/png', width: 1200, height: 400 }, now);
    let updated = await banners.updateBanner(String(admin), banner.id, { expectedVersion: 0, mediaId: media.id, reason: 'Attach local banner image' }, now, context);
    updated = await banners.updateBanner(String(admin), banner.id, { expectedVersion: updated.version, status: 'active', reason: 'Publish overlapping homepage banners' }, now, context);
    assert.equal(updated.keepOriginalHero, keepOriginalHero);
  }
  assert.equal((await readPublishedBannerRows(db, now)).length, 2);
  home = await homepage();
  assert.deepEqual(home.banners.map(row => row.keepOriginalHero), [true, false]);
  report.checks.push('Two simultaneous published homepage banners coexist; original-intro choice survives DB and public contract');
  const realProperty = new Types.ObjectId(), trialProperty = new Types.ObjectId();
  await db.collection('properties').insertMany([{ _id: realProperty, name: 'Keep real property' }, { _id: trialProperty, name: 'Manual trial property' }]);
  await db.collection('sessions').insertOne({ userId: admin, tokenHash: 'keep-admin-session' });
  let manifest = await planTrialCleanup(db);
  assert.equal(manifest.records.some(row => row.collection === 'users' && String(mongoose.mongo.BSON.EJSON.parse(row.id)) === String(admin)), false);
  assert.equal(manifest.records.some(row => row.collection === 'admin_credentials'), false);
  assert.equal(manifest.records.some(row => row.collection === 'admin_settings'), false);
  assert.equal(await db.collection('properties').countDocuments({}), 2);
  manifest.records.find(row => row.collection === 'properties' && String(mongoose.mongo.BSON.EJSON.parse(row.id)) === String(trialProperty)).selected = true;
  await db.collection('properties').updateOne({ _id: trialProperty }, { $set: { version: 1 } });
  await assert.rejects(applyTrialCleanup(db, manifest, output), /PLAN_STALE/);
  manifest = await planTrialCleanup(db);
  manifest.records.find(row => row.collection === 'properties' && String(mongoose.mongo.BSON.EJSON.parse(row.id)) === String(trialProperty)).selected = true;
  const applied = await applyTrialCleanup(db, manifest, output);
  assert.equal(applied.deleted, 1);
  assert.equal(await db.collection('properties').countDocuments({ _id: realProperty }), 1);
  const backup = mongoose.mongo.BSON.EJSON.parse(await readFile(applied.backupFile, 'utf8'));
  assert.equal(backup.records[0].document.name, 'Manual trial property');
  await db.collection('properties').insertOne(backup.records[0].document);
  assert.equal((await db.collection('properties').findOne({ _id: trialProperty })).name, 'Manual trial property');
  const linkedProject = new Types.ObjectId();
  await db.collection('projects').insertOne({ _id: linkedProject, name: 'Trial project with retained property' });
  await db.collection('properties').updateOne({ _id: realProperty }, { $set: { projectId: linkedProject } });
  manifest = await planTrialCleanup(db);
  manifest.records.find(row => row.collection === 'projects' && String(mongoose.mongo.BSON.EJSON.parse(row.id)) === String(linkedProject)).selected = true;
  await assert.rejects(applyTrialCleanup(db, manifest, output), /UNSELECTED_DEPENDENT/);
  assert.equal(await db.collection('projects').countDocuments({ _id: linkedProject }), 1);
  manifest = await planTrialCleanup(db); manifest.records.forEach(row => { row.selected = true; });
  await applyTrialCleanup(db, manifest, output);
  assert.equal(await db.collection('users').countDocuments({}), 1);
  assert.equal(await db.collection('admin_credentials').countDocuments({}), 1);
  assert.equal(await db.collection('sessions').countDocuments({}), 1);
  assert.equal(await db.collection('admin_settings').countDocuments({}), 1);
  report.checks.push('Cleanup preview writes no data; manual record listed; stale plan refused; deleted record restored from EJSON backup; unselected real content retained; unselected dependent blocks deletion; full reviewed cleanup preserves admin credentials/session/settings');
  report.status = 'PASS_LOCAL';
} catch (error) { report.status = 'FAIL_LOCAL'; report.error = error.stack; process.exitCode = 1; }
finally {
  assert.equal(db.name, dbName); await db.dropDatabase(); await db.close(); report.cleanup = true;
  await rm(output, { recursive: true, force: true });
  await writeFile('docs/quality/guide-runs/owner-oct24-guarantees-local-latest.json', JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify(report, null, 2));
}
